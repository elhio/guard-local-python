class TestVerdict:
    def test_evidence_from_an_ingredient_decides_the_verdict(self) -> None:
        """
        Ensure a generated-then-edited image is still caught.

        The active manifest records only a crop; the generation is recorded one level
        down, which is exactly the case the chain walk exists for.
        """
        store = manifest_store(
            "urn:edit",
            **{
                "urn:edit": manifest(
                    "urn:edit",
                    claim_generator="Photoshop/25.0",
                    actions=[{"action": "c2pa.cropped"}],
                    ingredients=[{"active_manifest": "urn:origin"}],
                ),
                "urn:origin": manifest(
                    "urn:origin", actions=[{"action": "c2pa.ai_generated"}]
                ),
            },
        )

        result = detect_ai_generation(get_manifest_chain(store))

        assert result.confidence == 95
        assert result.detected is True

    def test_matches_come_back_loudest_first(self) -> None:
        store = manifest_store(
            "urn:a",
            **{
                "urn:a": manifest(
                    "urn:a",
                    claim_generator="Midjourney/6",
                    actions=[
                        {
                            "action": "c2pa.ai_generated",
                            "digitalSourceType": TRAINED_ALGORITHMIC,
                        }
                    ],
                )
            },
        )

        result = detect_ai_generation(get_manifest_chain(store))

        assert [m.confidence for m in result.matches] == [95, 90, 80]

    def test_an_empty_chain_is_a_clean_zero(self) -> None:
        result = detect_ai_generation([])

        assert result.confidence == 0
        assert result.detected is False
        assert result.matches == []

    def test_every_match_names_c2pa_as_its_source(self) -> None:
        """The engine mixes layers, so each match must say where it came from."""
        store = manifest_store(
            "urn:a",
            **{"urn:a": manifest("urn:a", actions=[{"action": "c2pa.ai_generated"}])},
        )

        result = detect_ai_generation(get_manifest_chain(store))

        assert all(m.source == "c2pa" for m in result.matches)


class TestReader:
    def test_unsigned_media_reads_as_no_manifest(self) -> None:
        """
        Ensure the common case is silent.

        Most media carries no manifest at all, so this path must be an empty result
        rather than an exception.
        """
        assert read_manifest_chain(png_bytes(), "image/png") == []
        assert read_manifest_chain(jpeg_bytes(), "image/jpeg") == []

    def test_corrupt_bytes_never_raise(self) -> None:
        assert read_manifest_chain(b"not media at all", "image/jpeg") == []

    def test_an_unsupported_container_never_raises(self) -> None:
        """
        Ensure an unreadable container does not sink the whole scan.

        The metadata and model layers are independent of this one and must still get
        to report.
        """
        assert read_manifest_chain(png_bytes(), "video/quicktime") == []
